#!/usr/bin/env node
/**
 * SAFE one-way sync: production public API  ->  local dev database.
 *
 *   - Reads production ONLY over HTTPS GET (never writes to it).
 *   - Emits idempotent SQL to db-dumps/import-prod.sql:
 *       * only rows whose Id is NOT already in the local DB are inserted,
 *         so re-running never duplicates and never touches existing rows;
 *       * production Ids / slugs / FK relationships are preserved exactly.
 *   - You pipe that SQL into the LOCAL postgres yourself (script prints how).
 *   - /uploads/* image paths are rewritten to https://devliora.com/uploads/*
 *     so images load in local dev without copying files.
 *
 * Usage:
 *   node infra/scripts/import-prod-api-to-local.mjs \
 *     --api https://devliora.com/api \
 *     --existing-ids db-dumps/local-ids.json     # produced by the wrapper
 *   docker exec -i devliora-postgres psql -U agencyadmin -d devliora < db-dumps/import-prod.sql
 */
import { writeFileSync, readFileSync, mkdirSync } from "node:fs";

const arg = (k, d) => {
  const i = process.argv.indexOf(k);
  return i > -1 ? process.argv[i + 1] : d;
};
const API = (arg("--api", "https://devliora.com/api")).replace(/\/$/, "");
const EXISTING = JSON.parse(readFileSync(arg("--existing-ids", "db-dumps/local-ids.json"), "utf8"));
const OUT = arg("--out", "db-dumps/import-prod.sql");

const PROD_ORIGIN = new URL(API).origin;
// EXISTING["Table"] = [ids...]; EXISTING["Table__slugs"] = [slugs...]
const has = (table, id) => (EXISTING[table] || []).includes(id);
const hasSlug = (table, slug) => (EXISTING[table + "__slugs"] || []).includes(slug);
const q = (v) => {
  if (v === null || v === undefined) return "NULL";
  return "'" + String(v).replace(/'/g, "''") + "'";
};
const img = (v) => {
  if (!v) return "";
  return String(v).startsWith("/uploads/") ? PROD_ORIGIN + v : String(v);
};
const arr = (a) =>
  !a || a.length === 0
    ? "ARRAY[]::text[]"
    : "ARRAY[" + a.map((x) => q(x)).join(",") + "]::text[]";
const bool = (b) => (b ? "true" : "false");
const ts = (v) => (v ? q(v) : "now()");
const uuid = () => crypto.randomUUID();

async function get(path) {
  const r = await fetch(API + path, { headers: { accept: "application/json" } });
  if (!r.ok) throw new Error(`GET ${path} -> ${r.status}`);
  return r.json();
}

const lines = [];
const p = (s) => lines.push(s);
const counts = {};
const bump = (k, n = 1) => (counts[k] = (counts[k] || 0) + n);

p("-- Generated by import-prod-api-to-local.mjs. Idempotent: INSERT ... ON CONFLICT DO NOTHING,");
p("-- and only rows missing from the local DB at generation time are emitted.");
p("BEGIN;");
p("SET session_replication_role = replica;  -- defer FK checks within this tx");

// ---------- Testimonials (referenced by Portfolios) ----------
for (const t of await get("/testimonials")) {
  if (has("Testimonials", t.id)) continue;
  p(`INSERT INTO "Testimonials" ("Id","ClientName","ClientTitle","ClientCompany","ClientPhotoUrl","Quote","Rating","IsFeatured","CreatedAt","UpdatedAt","IsDeleted") VALUES (${q(t.id)},${q(t.clientName)},${q(t.clientTitle)},${q(t.clientCompany)},${q(img(t.clientPhotoUrl))},${q(t.quote)},${t.rating ?? 5},${bool(t.isFeatured)},now(),NULL,false) ON CONFLICT ("Id") DO NOTHING;`);
  bump("Testimonials");
}

// ---------- CaseStudies (referenced by Services.tabCaseStudies) ----------
for (const c of await get("/case-studies")) {
  if (has("CaseStudies", c.id) || hasSlug("CaseStudies", c.slug)) continue;
  p(`INSERT INTO "CaseStudies" ("Id","Title","Slug","ClientName","Industry","Challenge","Solution","Results","CoverImageUrl","IsPublished","CreatedAt","UpdatedAt","IsDeleted") VALUES (${q(c.id)},${q(c.title)},${q(c.slug)},${q(c.clientName)},${q(c.industry)},${q(c.challenge)},${q(c.solution)},${q(c.results)},${q(img(c.coverImageUrl))},true,now(),NULL,false) ON CONFLICT ("Id") DO NOTHING;`);
  bump("CaseStudies");
}

// ---------- Services (+ highlights, industryCards, tabCaseStudies) ----------
for (const s of await get("/services")) {
  if (has("Services", s.id) || hasSlug("Services", s.slug)) continue;
  p(`INSERT INTO "Services" ("Id","Title","Slug","ShortDescription","FullDescription","IconUrl","DisplayOrder","IsActive","CreatedAt","UpdatedAt","IsDeleted","Includes","HeroImageUrl","ToolNames","ToolsDescription","ToolsHeading","ToolsTagline","ProcessGroupCount","ProcessGroupLabel","ProcessGroupStart","ProcessSteps","IndustriesDescription","IndustriesHeading","IndustriesTagline","HighlightsDescription","HighlightsHeading","AiServicesImageUrl","AdvancedTechnologiesImageUrl") VALUES (` +
    [
      q(s.id), q(s.title), q(s.slug), q(s.shortDescription), q(s.fullDescription),
      q(img(s.iconUrl)), s.displayOrder ?? 0, "true", "now()", "NULL", "false",
      arr(s.includes), q(img(s.heroImageUrl)), arr(s.toolNames),
      q(s.toolsDescription || ""), q(s.toolsHeading || ""), q(s.toolsTagline || ""),
      s.processGroupCount ?? 0, q(s.processGroupLabel || ""), s.processGroupStart ?? 0,
      arr(s.processSteps),
      q(s.industriesDescription || ""), q(s.industriesHeading || ""), q(s.industriesTagline || ""),
      q(s.highlightsDescription || ""), q(s.highlightsHeading || ""),
      q(img(s.aiServicesImageUrl)), q(img(s.advancedTechnologiesImageUrl)),
    ].join(",") + `) ON CONFLICT ("Id") DO NOTHING;`);
  bump("Services");
  for (const h of s.highlights || []) {
    p(`INSERT INTO "ServiceHighlights" ("Id","ServiceId","Label","Description","DisplayOrder","CreatedAt","UpdatedAt","IsDeleted") VALUES (${q(uuid())},${q(s.id)},${q(h.label)},${q(h.description)},${h.displayOrder ?? 0},now(),NULL,false);`);
    bump("ServiceHighlights");
  }
  for (const c of s.industryCards || []) {
    p(`INSERT INTO "ServiceIndustryCards" ("Id","ServiceId","ImageUrl","Title","Description","DisplayOrder","CreatedAt","UpdatedAt","IsDeleted") VALUES (${q(uuid())},${q(s.id)},${q(img(c.imageUrl))},${q(c.title)},${q(c.description)},${c.displayOrder ?? 0},now(),NULL,false);`);
    bump("ServiceIndustryCards");
  }
  for (const tc of s.tabCaseStudies || []) {
    const csId = tc.caseStudyId || tc.caseStudy?.id;
    if (!csId) continue;
    p(`INSERT INTO "ServiceTabCaseStudies" ("Id","ServiceId","Tab","CaseStudyId","DisplayOrder","CreatedAt","UpdatedAt","IsDeleted") VALUES (${q(uuid())},${q(s.id)},${q(tc.tab || "")},${q(csId)},${tc.displayOrder ?? 0},now(),NULL,false);`);
    bump("ServiceTabCaseStudies");
  }
}

// ---------- Portfolios (+ images, metrics) ----------
const portList = await get("/portfolios");
for (const pl of portList) {
  if (has("Portfolios", pl.id) || hasSlug("Portfolios", pl.slug)) continue;
  const d = await get(`/portfolios/${pl.slug}`).catch(() => pl);
  p(`INSERT INTO "Portfolios" ("Id","Title","Slug","ClientName","Summary","ThumbnailUrl","ProjectUrl","TechStack","IsFeatured","DisplayOrder","CreatedAt","UpdatedAt","IsDeleted","Approach","Challenge","Industry","Result","TestimonialId") VALUES (` +
    [
      q(d.id), q(d.title), q(d.slug), q(d.clientName || ""), q(d.summary || ""),
      q(img(d.thumbnailUrl)), q(d.projectUrl || ""), q(d.techStack || ""),
      bool(d.isFeatured), d.displayOrder ?? 0, "now()", "NULL", "false",
      q(d.approach || ""), q(d.challenge || ""), q(d.industry || ""), q(d.result || ""),
      d.testimonialId ? q(d.testimonialId) : "NULL",
    ].join(",") + `) ON CONFLICT ("Id") DO NOTHING;`);
  bump("Portfolios");
  for (const im of d.images || []) {
    p(`INSERT INTO "PortfolioImages" ("Id","PortfolioId","ImageUrl","Caption","DisplayOrder","CreatedAt","UpdatedAt","IsDeleted") VALUES (${q(uuid())},${q(d.id)},${q(img(im.imageUrl))},${q(im.caption || "")},${im.displayOrder ?? 0},now(),NULL,false);`);
    bump("PortfolioImages");
  }
  for (const m of d.metrics || []) {
    p(`INSERT INTO "PortfolioMetrics" ("Id","PortfolioId","Label","Value","DisplayOrder","CreatedAt","UpdatedAt","IsDeleted") VALUES (${q(uuid())},${q(d.id)},${q(m.label)},${q(m.value)},${m.displayOrder ?? 0},now(),NULL,false);`);
    bump("PortfolioMetrics");
  }
}

// ---------- Partners ----------
for (const pt of await get("/partners")) {
  if (has("Partners", pt.id)) continue;
  p(`INSERT INTO "Partners" ("Id","Name","LogoUrl","WebsiteUrl","DisplayOrder","IsActive","CreatedAt","UpdatedAt","IsDeleted") VALUES (${q(pt.id)},${q(pt.name)},${q(img(pt.logoUrl))},${q(pt.websiteUrl || "")},${pt.displayOrder ?? 0},true,now(),NULL,false) ON CONFLICT ("Id") DO NOTHING;`);
  bump("Partners");
}

// ---------- BlogPosts (detail endpoint for content) ----------
for (const b of await get("/blog-posts")) {
  if (has("BlogPosts", b.id) || hasSlug("BlogPosts", b.slug)) continue;
  const d = await get(`/blog-posts/${b.slug}`).catch(() => b);
  p(`INSERT INTO "BlogPosts" ("Id","Title","Slug","Excerpt","Content","CoverImageUrl","AuthorName","Status","PublishedAt","CreatedAt","UpdatedAt","IsDeleted") VALUES (${q(d.id)},${q(d.title)},${q(d.slug)},${q(d.excerpt || "")},${q(d.content || "")},${q(img(d.coverImageUrl))},${q(d.authorName || "")},1,${ts(d.publishedAt)},now(),${d.updatedAt ? q(d.updatedAt) : "NULL"},false) ON CONFLICT ("Id") DO NOTHING;`);
  bump("BlogPosts");
}

// ---------- OfficeLocations ----------
for (const o of await get("/office-locations")) {
  if (has("OfficeLocations", o.id)) continue;
  p(`INSERT INTO "OfficeLocations" ("Id","Country","Address","Phone","Email","MapQuery","DisplayOrder","IsActive","CreatedAt","UpdatedAt","IsDeleted") VALUES (${q(o.id)},${q(o.country)},${q(o.address || "")},${q(o.phone || "")},${q(o.email || "")},${q(o.mapQuery || "")},${o.displayOrder ?? 0},true,now(),NULL,false) ON CONFLICT ("Id") DO NOTHING;`);
  bump("OfficeLocations");
}

// ---------- TechnologyDetailPages (= Solutions + Technology detail; + features, faqs, serviceCards) ----------
for (const tp of await get("/technology-detail-pages")) {
  // local seed rows use runtime-random GUIDs, so match by slug not id
  if (has("TechnologyDetailPages", tp.id) || hasSlug("TechnologyDetailPages", tp.slug)) continue;
  const d = await get(`/technology-detail-pages/${tp.slug}`).catch(() => null);
  if (!d) continue;
  p(`INSERT INTO "TechnologyDetailPages" ("Id","Slug","TechnologyName","MetaDescription","DisplayOrder","HeroTitle","OverviewHeading","OverviewHeadingAccent","OverviewParagraph","HighlightHeadline","HighlightParagraph","IndustriesParagraph","ServicesHeading","ServicesCardLabel","ServicesParagraph","CreatedAt","UpdatedAt","IsDeleted","IndustriesImageUrl","ServicesCardImageUrl","HeroImageUrl","OverviewHeadingSuffix","PageType","ShowTechnologiesShowcase") VALUES (` +
    [
      q(d.id), q(d.slug), q(d.technologyName || ""), q(d.metaDescription || ""), d.displayOrder ?? 0,
      q(d.heroTitle || ""), q(d.overviewHeading || ""), q(d.overviewHeadingAccent || ""), q(d.overviewParagraph || ""),
      q(d.highlightHeadline || ""), q(d.highlightParagraph || ""), q(d.industriesParagraph || ""),
      q(d.servicesHeading || ""), q(d.servicesCardLabel || ""), q(d.servicesParagraph || ""),
      "now()", "NULL", "false",
      q(img(d.industriesImageUrl)), q(img(d.servicesCardImageUrl)), q(img(d.heroImageUrl)),
      q(d.overviewHeadingSuffix || ""), q(d.pageType || "technology"), bool(d.showTechnologiesShowcase),
    ].join(",") + `) ON CONFLICT ("Id") DO NOTHING;`);
  bump("TechnologyDetailPages");
  for (const f of d.features || []) {
    p(`INSERT INTO "TechnologyDetailFeatures" ("Id","TechnologyDetailPageId","Title","Body","DisplayOrder","CreatedAt","UpdatedAt","IsDeleted") VALUES (${q(uuid())},${q(d.id)},${q(f.title)},${q(f.body)},${f.displayOrder ?? 0},now(),NULL,false);`);
    bump("TechnologyDetailFeatures");
  }
  for (const f of d.faqs || []) {
    p(`INSERT INTO "TechnologyDetailFaqs" ("Id","TechnologyDetailPageId","Question","Answer","DisplayOrder","CreatedAt","UpdatedAt","IsDeleted") VALUES (${q(uuid())},${q(d.id)},${q(f.question)},${q(f.answer)},${f.displayOrder ?? 0},now(),NULL,false);`);
    bump("TechnologyDetailFaqs");
  }
  for (const sc of d.services || []) {
    p(`INSERT INTO "TechnologyDetailServiceCards" ("Id","TechnologyDetailPageId","Title","Description","DisplayOrder","CreatedAt","UpdatedAt","IsDeleted") VALUES (${q(uuid())},${q(d.id)},${q(sc.title)},${q(sc.description)},${sc.displayOrder ?? 0},now(),NULL,false);`);
    bump("TechnologyDetailServiceCards");
  }
}

p("SET session_replication_role = DEFAULT;");
p("COMMIT;");

mkdirSync("db-dumps", { recursive: true });
writeFileSync(OUT, lines.join("\n") + "\n");

console.error("Generated " + OUT);
console.error(JSON.stringify(counts, null, 2));
